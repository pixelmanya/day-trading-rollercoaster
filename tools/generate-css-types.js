/**
 * Writes a typed declaration next to every CSS module (Hero.module.css → Hero.module.d.css.ts),
 * so `styles.hero` is a string and a misspelled class is a type error. TypeScript picks these
 * up through `allowArbitraryExtensions`. The files are generated, git-ignored and rebuilt by
 * `pnpm typecheck` and `pnpm build`.
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const sourceRoot = 'src'
const classPattern = /\.([a-zA-Z][\w-]*)/g
const commentPattern = /\/\*[\s\S]*?\*\//g

function findModuleFiles(root) {
  return readdirSync(root, { recursive: true })
    .filter((filePath) => filePath.endsWith('.module.css'))
    .map((filePath) => join(root, filePath))
}

function collectClassNames(stylesheet) {
  const classNames = stylesheet
    .replaceAll(commentPattern, '')
    .matchAll(classPattern)
    .map(([, className]) => className)

  return [...new Set(classNames)].toSorted()
}

function renderDeclaration(classNames) {
  const fields = classNames.map((className) => `  readonly ${className}: string`).join('\n')

  return [
    '// Generated by tools/generate-css-types.js. Do not edit.',
    `declare const styles: {\n${fields}\n}`,
    'export default styles',
    '',
  ].join('\n\n')
}

function writeDeclaration(stylesheetPath) {
  const declarationPath = stylesheetPath.replace(/\.css$/, '.d.css.ts')
  const classNames = collectClassNames(readFileSync(stylesheetPath, 'utf8'))

  writeFileSync(declarationPath, renderDeclaration(classNames))
}

findModuleFiles(sourceRoot).forEach((stylesheetPath) => writeDeclaration(stylesheetPath))
